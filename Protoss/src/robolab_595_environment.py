"""Generate an isolated uv project from the pinned upstream package metadata.

Do not select RoboLab's `isaac51` extra: install Sim 6.0.1 explicitly with
the matching Isaac Lab workspace packages.
The generated uv.lock records the full resolved environment on the GPU server.
"""

import copy
import json
from pathlib import Path
import sys
import tomllib


def environment(stack: Path) -> dict:
    lab_root = stack / "IsaacLab"
    lab = tomllib.loads((lab_root / "pyproject.toml").read_text())
    uv = copy.deepcopy(lab["tool"]["uv"])
    # Resolve actual metadata constraints; do not mask a NumPy conflict with
    # the dev workspace's blanket override (pip check would still reject it).
    uv.pop("override-dependencies", None)
    uv["environments"] = ["sys_platform == 'linux' and platform_machine == 'x86_64'"]
    for source in uv["sources"].values():
        if isinstance(source, dict) and "path" in source:
            source["path"] = str((lab_root / source["path"]).resolve())
    uv["sources"]["robolab"] = {"path": str((stack / "RoboLab").resolve()), "editable": True}
    # Constraints from the pinned simulator must also constrain RoboLab's
    # unbounded fastapi/numpy dependencies in the same resolver transaction.
    # Only inference/PhysX packages are needed. The full Lab dev workspace
    # includes RL trainers with incompatible packaging pins and Newton tasks.
    # Sim 6.0.1 pins torchvision 0.26, paired with torch 2.11.
    dependencies = ["isaaclab", "isaaclab-physx", "isaaclab-ov",
                    "torch==2.11.0", "torchvision==0.26.0",
                    "isaacsim[all,extscache]==6.0.1.0", "robolab"]
    return {
        "project": {
            "name": "protoss-robolab-595", "version": "0.1.0",
            "requires-python": ">=3.12,<3.13", "dependencies": dependencies,
        },
        "tool": {"uv": uv},
    }


def write_project(stack: Path) -> None:
    # JSON string/array syntax is also valid TOML; emit nested tables explicitly.
    def inline(value):
        if isinstance(value, bool):
            return str(value).lower()
        if isinstance(value, dict):
            return "{ " + ", ".join(f"{json.dumps(k)} = {inline(v)}" for k, v in value.items()) + " }"
        if isinstance(value, list):
            return "[" + ", ".join(inline(v) for v in value) + "]"
        return json.dumps(value)

    data = environment(stack)
    lines = ["# Generated by Protoss; experimental Isaac Sim 6.0 stack.", "[project]"]
    lines += [f"{key} = {json.dumps(value)}" for key, value in data["project"].items()]
    uv = data["tool"]["uv"]
    lines += ["", "[tool.uv]"]
    for key, value in uv.items():
        if key not in {"sources", "index"}:
            lines.append(f"{key} = {inline(value)}")
    for index in uv.get("index", []):
        lines += ["", "[[tool.uv.index]]"]
        lines += [f"{key} = {str(value).lower() if isinstance(value, bool) else json.dumps(value)}" for key, value in index.items()]
    lines += ["", "[tool.uv.sources]"]
    lines += [f"{json.dumps(key)} = {inline(value)}" for key, value in uv["sources"].items()]
    text = "\n".join(lines) + "\n"
    tomllib.loads(text)  # Refuse to replace the manifest with invalid TOML.
    (stack / "pyproject.toml").write_text(text)


if __name__ == "__main__":
    write_project(Path(sys.argv[1]).resolve())
